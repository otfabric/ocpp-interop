// Command gen writes actions_gen.go: for every action of seanlee0923/ocpp's
// generated payload packages (v16, v201, v21), the typed calls and handler
// registrations of csms and station, through the generic helpers of
// ops.go. seanlee0923/ocpp's Call and Handle are generic over the payload
// types; the fixtures and the contract are JSON, so the adapter needs one
// instantiation per action. Run from adapters/seanlee: go run ./gen
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// gofmt keeps a short method on one line and wraps a long one.
var actionRE = regexp.MustCompile(`(?m)^func \((\w+)(Request|Confirmation)\) ActionName\(\) string \{\s*return "(\w+)"\s*\}`)

func main() {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "github.com/seanlee0923/ocpp").Output()
	if err != nil {
		fail(err)
	}
	dir := strings.TrimSpace(string(out))
	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./gen; DO NOT EDIT.\n\n// SPDX-License-Identifier: MIT\npackage main\n\n")
	b.WriteString("import (\n\t\"github.com/seanlee0923/ocpp/v16\"\n\t\"github.com/seanlee0923/ocpp/v201\"\n\t\"github.com/seanlee0923/ocpp/v21\"\n)\n\n")
	b.WriteString("// actionTable: the actions seanlee0923/ocpp has types for, per OCPP version.\nvar actionTable = map[string]map[string]actionOps{\n")
	for _, v := range []struct{ name, pkg string }{{"1.6", "v16"}, {"2.0.1", "v201"}, {"2.1", "v21"}} {
		files, err := filepath.Glob(filepath.Join(dir, v.pkg, "*.go"))
		if err != nil {
			fail(err)
		}
		reqs, confs := map[string]string{}, map[string]string{}
		for _, f := range files {
			if strings.HasSuffix(f, "_test.go") {
				continue
			}
			data, err := os.ReadFile(f)
			if err != nil {
				fail(err)
			}
			for _, m := range actionRE.FindAllStringSubmatch(string(data), -1) {
				if m[2] == "Request" {
					reqs[m[3]] = m[1]
				} else {
					confs[m[3]] = m[1]
				}
			}
		}
		actions := make([]string, 0, len(reqs))
		for a := range reqs {
			actions = append(actions, a)
		}
		sort.Strings(actions)
		fmt.Fprintf(&b, "\t%q: {\n", v.name)
		for _, a := range actions {
			q := v.pkg + "." + reqs[a] + "Request"
			if base, ok := confs[a]; ok {
				c := v.pkg + "." + base + "Confirmation"
				fmt.Fprintf(&b, "\t\t%q: callOps[%s, %s](),\n", a, q, c)
			} else {
				fmt.Fprintf(&b, "\t\t%q: sendOps[%s](),\n", a, q)
			}
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile("actions_gen.go", src, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}
